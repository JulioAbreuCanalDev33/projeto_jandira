create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------------------

create table if not exists public.modalidades_esporte (
  id integer generated by default as identity primary key,
  nome varchar(80) not null,
  descricao text,
  data_cadastro timestamp not null default now()
);

create table if not exists public.cadastro_atletas (
  id integer generated by default as identity primary key,
  foto text not null default '',
  nome text not null,
  rg text not null default '',
  cpf text not null default '',
  endereco text not null default '',
  numero text not null default '',
  cep text not null default '',
  municipio text not null default '',
  cidade text not null default '',
  data_nascimento date not null,
  email text,
  senha text not null,
  telefone text not null default '',
  modalidade_esporte_id integer references public.modalidades_esporte (id) on delete set null,
  data_cadastro timestamp not null default now()
);

create table if not exists public.arquivos (
  id integer generated by default as identity primary key,
  nome text not null,
  path text not null,
  data_upload timestamp not null default now()
);

create table if not exists public.eventos (
  id integer generated by default as identity primary key,
  titulo text not null,
  descricao text,
  data_inicio timestamp not null,
  data_fim timestamp not null
);

create table if not exists public.senhas (
  id integer generated by default as identity primary key,
  senha text not null,
  email text not null
);

create table if not exists public.sessoes (
  id text primary key,
  dados text not null default '',
  atualizado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Índices e restrições
-- ---------------------------------------------------------------------------

create unique index if not exists uq_modalidades_esporte_nome
  on public.modalidades_esporte (nome);

create unique index if not exists uq_senhas_email
  on public.senhas (email);

create index if not exists idx_atletas_modalidade_esporte
  on public.cadastro_atletas (modalidade_esporte_id);

create index if not exists idx_eventos_data_inicio
  on public.eventos (data_inicio desc);

create index if not exists idx_arquivos_data_upload
  on public.arquivos (data_upload desc, id desc);

